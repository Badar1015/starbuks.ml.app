"""### 4. Data Splitting and Decision Tree Model
We will preprocess the features (handling categorical columns if any by encoding them) and then split the dataset into train and test sets to train a Decision Tree Classifier.
"""

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import accuracy_score, classification_report
import pandas as pd

# Drop irrelevant columns for features (like 'Unnamed: 0' / product name and the original continuous 'Calories' column)
