import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

# Load the drinks dataset
drink_file = '/content/dataset/starbucks_drinkMenu_expanded.csv'
df_drinks = pd.read_csv(drink_file)

# Clean column names by stripping spaces
df_drinks.columns = df_drinks.columns.str.strip()

# Create a target column (High vs Low Calories) using the median of drinks calories
median_drink_cal = df_drinks['Calories'].median()
df_drinks['Calorie_Category'] = np.where(df_drinks['Calories'] >= median_drink_cal, 'High Calorie', 'Low Calorie')

# Select features and target
# Drop columns that are text identifiers or target leakage
features_to_drop = ['Beverage_category', 'Beverage', 'Beverage_prep', 'Calories', 'Calorie_Category']
X_dr = df_drinks.drop(columns=[col for col in features_to_drop if col in df_drinks.columns])
y_dr = df_drinks['Calorie_Category']

# Convert object columns to numeric (removing '%' signs if any) or one-hot encode
for col in X_dr.columns:
    if X_dr[col].dtype == 'object':
        X_dr[col] = X_dr[col].str.replace('%', '').str.strip()
        X_dr[col] = pd.to_numeric(X_dr[col], errors='coerce')

# Fill any NaNs
X_dr = X_dr.fillna(0)

# Split into train/test
X_dr_train, X_dr_test, y_dr_train, y_dr_test = train_test_split(X_dr, y_dr, test_size=0.2, random_state=42)

# Train Decision Tree
clf_dr = DecisionTreeClassifier(max_depth=3, random_state=42)
clf_dr.fit(X_dr_train, y_dr_train)

# Predict
y_dr_pred = clf_dr.predict(X_dr_test)

# Create a comparison table for 10 drinks
drink_comparison = pd.DataFrame({
    'Drink Name': df_drinks.loc[X_dr_test.index, 'Beverage'],
    'Prep': df_drinks.loc[X_dr_test.index, 'Beverage_prep'],
    'Actual Category': y_dr_test,
    'Predicted Category': y_dr_pred
})

display(drink_comparison.head(10))